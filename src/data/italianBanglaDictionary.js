function getRegularVerbForms(infinitive, group) {
  const ending = group === "isc" ? "ire" : group;
  const stem = infinitive.slice(0, -3);

  let presentEndings;

  if (group === "are") {
    presentEndings = ["o", "i", "a", "iamo", "ate", "ano"];
  } else if (group === "ere") {
    presentEndings = ["o", "i", "e", "iamo", "ete", "ono"];
  } else if (group === "isc") {
    presentEndings = ["isco", "isci", "isce", "iamo", "ite", "iscono"];
  } else {
    presentEndings = ["o", "i", "e", "iamo", "ite", "ono"];
  }

  const imperfectEndings =
    ending === "are"
      ? ["avo", "avi", "ava", "avamo", "avate", "avano"]
      : ending === "ere"
        ? ["evo", "evi", "eva", "evamo", "evate", "evano"]
        : ["ivo", "ivi", "iva", "ivamo", "ivate", "ivano"];

  function joinAreStem(baseStem, formEnding) {
    if (group !== "are") {
      return baseStem + formEnding;
    }

    if (
      /[cg]$/i.test(baseStem) &&
      /^i/i.test(formEnding)
    ) {
      return `${baseStem}h${formEnding}`;
    }

    if (
      /[cg]i$/i.test(baseStem) &&
      /^i/i.test(formEnding)
    ) {
      return baseStem.slice(0, -1) + formEnding;
    }

    return baseStem + formEnding;
  }

  return {
    present: presentEndings.map((formEnding) =>
      joinAreStem(stem, formEnding)
    ),
    imperfect: imperfectEndings.map((formEnding) =>
      stem + formEnding
    ),
    gerund:
      stem +
      (ending === "are" ? "ando" : "endo")
  };
}

function addDictionaryEntry(word, entry) {
  const safeWord = String(word || "")
    .normalize("NFC")
    .trim()
    .toLocaleLowerCase("it-IT");

  if (!safeWord || italianBanglaDictionary[safeWord]) {
    return;
  }

  italianBanglaDictionary[safeWord] = entry;
}

italianVerbDefinitions.forEach((verb) => {
  const forms = getRegularVerbForms(
    verb.infinitive,
    verb.group
  );

  addDictionaryEntry(verb.infinitive, {
    bn: verb.bn,
    explanation:
      `এটি ইতালীয় ক্রিয়ার মূল বা infinitive রূপ। অর্থ: ${verb.bn}।`,
    exampleItalian:
      `È importante ${verb.infinitive} correttamente.`,
    exampleBangla:
      `সঠিকভাবে “${verb.bn}” গুরুত্বপূর্ণ।`,
    category: "verbo"
  });

  forms.present.forEach((form, index) => {
    const person = dictionaryPersons[index];

    addDictionaryEntry(form, {
      bn:
        `${verb.bn} — বর্তমানকাল (${person.labelBn})`,
      explanation:
        `“${form}” হলো “${verb.infinitive}” ক্রিয়ার presente indicativo, ${person.labelIt} রূপ। মূল অর্থ: ${verb.bn}।`,
      exampleItalian:
        `${person.labelIt.charAt(0).toUpperCase() + person.labelIt.slice(1)} ${form}.`,
      exampleBangla:
        `${person.labelBn} — ${verb.bn}।`,
      category: "verbo-presente",
      baseWord: verb.infinitive
    });
  });

  forms.imperfect.forEach((form, index) => {
    const person = dictionaryPersons[index];

    addDictionaryEntry(form, {
      bn:
        `${verb.bn} — অতীতে চলমান/অভ্যাসগত (${person.labelBn})`,
      explanation:
        `“${form}” হলো “${verb.infinitive}” ক্রিয়ার imperfetto, ${person.labelIt} রূপ। এটি অতীতে চলমান বা অভ্যাসগত কাজ বোঝায়।`,
      exampleItalian:
        `${person.labelIt.charAt(0).toUpperCase() + person.labelIt.slice(1)} ${form} spesso.`,
      exampleBangla:
        `${person.labelBn} আগে প্রায়ই এই কাজ করতাম/করত। অর্থ: ${verb.bn}।`,
      category: "verbo-imperfetto",
      baseWord: verb.infinitive
    });
  });

  addDictionaryEntry(forms.gerund, {
    bn: `${verb.bn} — করতে করতে/করছে`,
    explanation:
      `“${forms.gerund}” হলো “${verb.infinitive}” ক্রিয়ার gerundio রূপ। চলমান কাজ বোঝাতে ব্যবহৃত হয়।`,
    exampleItalian:
      `Sto ${forms.gerund}.`,
    exampleBangla:
      `আমি এখন কাজটি করছি: ${verb.bn}।`,
    category: "verbo-gerundio",
    baseWord: verb.infinitive
  });
});

