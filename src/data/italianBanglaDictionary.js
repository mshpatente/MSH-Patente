export function normalizeDictionaryWord(value) {
  return String(value || "")
    .normalize("NFC")
    .trim()
    .toLocaleLowerCase("it-IT")
    .replace(
      /^[^a-zà-öø-ÿ]+|[^a-zà-öø-ÿ]+$/giu,
      ""
    );
}

export function getItalianBanglaEntry(word) {
  const normalizedWord =
    normalizeDictionaryWord(word);

  if (!normalizedWord) {
    return null;
  }

  const entry =
    italianBanglaDictionary[
      normalizedWord
    ];

  if (!entry) {
    return null;
  }

  if (typeof entry === "string") {
    return {
      word: normalizedWord,
      bn: entry
    };
  }

  return {
    word: normalizedWord,
    ...entry
  };
}

export function getItalianBanglaEntries() {
  return Object.entries(
    italianBanglaDictionary
  )
    .map(([word, entry]) => ({
      word,
      ...(typeof entry === "string"
        ? { bn: entry }
        : entry)
    }))
    .sort((first, second) =>
      first.word.localeCompare(
        second.word,
        "it",
        { sensitivity: "base" }
      )
    );
}

export function searchItalianBanglaDictionary(
  query = ""
) {
  const safeQuery = String(query)
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .toLocaleLowerCase("it-IT")
    .trim();

  const entries =
    getItalianBanglaEntries();

  if (!safeQuery) {
    return entries;
  }

  return entries.filter((entry) =>
    [
      entry.word,
      entry.bn,
      entry.explanation,
      entry.exampleItalian,
      entry.exampleBangla
    ]
      .filter(Boolean)
      .join(" ")
      .normalize("NFD")
      .replace(/[\u0300-\u036f]/g, "")
      .toLocaleLowerCase("it-IT")
      .includes(safeQuery)
  );
}

